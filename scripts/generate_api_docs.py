#!/usr/bin/env python3
"""Write the docs site's method reference from the generated facade.

    python scripts/generate_api_docs.py --facade calimero_client_py/facade.py \
        --document openapi/openapi.json --out docs/src/content/docs/reference/methods.mdx

One table per group (`client.apps`, `client.orgs`, ...): each facade method
with its keyword arguments, its route, what it does (the operation's summary),
whether a passkey or the operator key answers a step-up, and the refusal codes
core's document lists for it. scripts/generate_openapi_client.py runs this
with the client, so the page is regenerated (and checked in CI) whenever the
document changes.
"""

import argparse
import ast
import json
import re
from pathlib import Path

HEADER = """---
title: Method reference
description: Every operation of the node API as a Client method, by group — generated from core's OpenAPI document.
sidebar:
  order: 2
---

{/* Generated by scripts/generate_api_docs.py from calimero_client_py/facade.py
    and openapi/openapi.json: do not edit. */}

Every route of the node's API is a method of a group on `Client`:
`client.<group>.<method>(...)`. Arguments are keyword-only; a method returns
the generated model of the answer (`client.json.<group>.<method>(...)` returns
the node's JSON instead). How the arguments, step-ups and answers work is in
[Using the client](/reference/client/).

In the tables, **passkey** marks a method that answers `412 CONFIRM_REQUIRED`
(with `confirm=`, or the client's `use_passkey`), and **operator** one that
answers `428 OPERATOR_SIGNATURE_REQUIRED` (with `operator_proof=`, or the
client's `use_operator_key` / `use_operator_signer`). *Refusals* are the error
codes the document lists for the method beyond the ones every call can get
(`UNAUTHENTICATED`, `FORBIDDEN`, `NOT_FOUND`, ...): see
[errors](/reference/errors/).

Generated from core {commit}.
"""

# Codes any call may answer; listing them on every row says nothing.
COMMON = {
    "UNAUTHENTICATED",
    "FORBIDDEN",
    "NOT_FOUND",
    "BAD_REQUEST",
    "INVALID_REQUEST",
    "WRONG_NODE",
    "UNAVAILABLE",
    "INTERNAL",
    "CONFIRM_REQUIRED",
    "OPERATOR_SIGNATURE_REQUIRED",
    "NOT_LEADER",
    "RATE_LIMITED",
    "TOO_LARGE",
    "PAYLOAD_TOO_LARGE",
    # The step-ups' own: the client answers the challenge.
    "EXPIRED_CHALLENGE",
    "UNKNOWN_CHALLENGE",
    "WRONG_CHALLENGE",
    "BAD_OPERATOR_SIGNATURE",
}


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def methods(facade: str):
    """`[(group, class name, [(method, args text, docstring)])]` in GROUPS order."""
    tree = ast.parse(facade)
    classes = {n.name: n for n in tree.body if isinstance(n, ast.ClassDef)}
    order = []
    for node in tree.body:
        target = getattr(node, "targets", [None])[0]
        if isinstance(target, ast.Name) and target.id == "GROUPS":
            order = [
                (k.value, v.id) for k, v in zip(node.value.keys, node.value.values)
            ]
    out = []
    for group, cls in order:
        rows = []
        for item in classes[cls].body:
            if isinstance(item, ast.FunctionDef) and not item.name.startswith("_"):
                args = item.args
                args.args = [a for a in args.args if a.arg != "self"]
                rows.append(
                    (item.name, ast.unparse(args), ast.get_docstring(item) or "")
                )
        out.append((group, rows))
    return out


def operations(document: dict) -> dict:
    """operationId -> (METHOD path, operation)."""
    found = {}
    for path, item in document["paths"].items():
        for method, op in item.items():
            if isinstance(op, dict) and "operationId" in op:
                found[op["operationId"]] = (f"{method.upper()} {path}", op)
    return found


def refusals(op: dict) -> list:
    codes = []
    for status, answer in sorted(op.get("responses", {}).items()):
        if status.startswith("2"):
            continue
        for code in answer.get("x-calimero-codes", []):
            if code not in COMMON and f"`{status} {code}`" not in codes:
                codes.append(f"`{status} {code}`")
    return codes


def render(facade: str, document: dict, commit: str) -> str:
    ops = operations(document)
    lines = [HEADER.replace("{commit}", f"`{commit[:9]}`" if commit else "")]
    for group, rows in methods(facade):
        lines += [f"## `client.{group}`", ""]
        lines += ["| Method | Route | What it does |", "| --- | --- | --- |"]
        for name, args, doc in rows:
            first = doc.split("\n", 1)[0]
            m = re.search(r"\(`([A-Z]+ [^`]+)`, `([^`]+)`\)\.?$", first)
            route, oid = (m.group(1), m.group(2)) if m else ("", "")
            summary = first[: m.start()].strip() if m else first
            _, op = ops.get(oid, ("", {}))
            marks = []
            if op.get("x-calimero-step-up"):
                when = op.get("x-calimero-step-up-when")
                marks.append("**passkey**" + (f" ({cell(when)})" if when else ""))
            if op.get("x-calimero-operator"):
                marks.append("**operator**")
            codes = refusals(op)
            what = cell(summary)
            if marks:
                what += ". " + ", ".join(marks)
            if codes:
                what += ". *Refusals:* " + ", ".join(codes)
            sig = args[3:] if args.startswith("*, ") else args
            # An argument left out is not sent: `args=…`.
            sig = sig.replace("=UNSET", "=…")
            lines.append(f"| `{name}({cell(sig)})` | `{route}` | {what} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--facade", type=Path, required=True)
    parser.add_argument("--document", type=Path, required=True)
    parser.add_argument("--source", type=Path, help="openapi/source.json")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    commit = ""
    if args.source and args.source.exists():
        commit = json.loads(args.source.read_text()).get("commit", "")
    args.out.write_text(
        render(args.facade.read_text(), json.loads(args.document.read_text()), commit)
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
